function hostedPlanOf(offer: SignUpOffer): string {
  return offersTheFreePlan(offer)
    ? `Hobby plan, free: ${FREE_PLAN_EVENTS} events a month on one site, no card; Pro plan: ${PRO_PLAN}`
    : '14-day free trial';
}

